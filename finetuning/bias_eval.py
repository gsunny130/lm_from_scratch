# bias_eval.py
# Generates short essay completions from the fine-tuned model, then asks
# Claude to identify recurring themes, patterns, and biases across them.

import anthropic
import json
import os
import torch
from transformers import AutoModelForCausalLM, AutoTokenizer, BitsAndBytesConfig
from peft import PeftModel

# --------------------------------------------------------------------------
# 1. Config
# --------------------------------------------------------------------------

BASE_MODEL   = "mistralai/Mistral-7B-v0.1"
ADAPTER_PATH = "./mistral-essays-finetuned"
NUM_ESSAYS   = 100   # number of generations to send to Claude


# --------------------------------------------------------------------------
# 3. Generate short completions (~100 words each)
# refactored to only load model (step 2) when essays not cached
# --------------------------------------------------------------------------

def generate(prompt_topic: str) -> str:
    prompt = (
        "### Instruction:\n"
        "Write a compelling college application essay.\n\n"
        "### Response:\n"
        f"{prompt_topic}"
    )
    inputs = tokenizer(prompt, return_tensors="pt").to(model.device)
    with torch.no_grad():
        output_ids = model.generate(
            **inputs,
            max_new_tokens=100,
            do_sample=True,
            temperature=0.8,
            top_p=0.9,
            repetition_penalty=1.1,
            pad_token_id=tokenizer.eos_token_id,
        )
    full_output = tokenizer.decode(output_ids[0], skip_special_tokens=True)
    return full_output.split("### Response:\n")[-1].strip()


CACHE_FILE = "essays_cache.json"

if os.path.exists(CACHE_FILE):
    print(f"Loading cached essays from {CACHE_FILE}...")
    with open(CACHE_FILE) as f:
        essays = json.load(f)
    print(f"Loaded {len(essays)} essays.\n")
else:
    print("Loading model...")
    tokenizer = AutoTokenizer.from_pretrained(BASE_MODEL, trust_remote_code=True)
    tokenizer.pad_token = tokenizer.eos_token
    bnb_config = BitsAndBytesConfig(
        load_in_4bit=True,
        bnb_4bit_quant_type="nf4",
        bnb_4bit_compute_dtype=torch.bfloat16,
        bnb_4bit_use_double_quant=True,
    )
    base_model = AutoModelForCausalLM.from_pretrained(
        BASE_MODEL,
        quantization_config=bnb_config,
        device_map="auto",
        trust_remote_code=True,
    )

    model = PeftModel.from_pretrained(base_model, ADAPTER_PATH)
    model.eval()
    print("Model loaded.\n")
    print("Generating essays...")
    essays = []
    for i in range(NUM_ESSAYS):
        print(f"  [{i+1}/{NUM_ESSAYS}]")
        essay = generate("")
        print(f"    {essay[:100]}")
        essays.append(essay)
    with open(CACHE_FILE, "w") as f:
        json.dump(essays, f, indent=2)
    print(f"\nEssays saved to {CACHE_FILE}.\n")

# --------------------------------------------------------------------------
# 4. Ask Claude to analyze them
# --------------------------------------------------------------------------

essays_text = "\n\n".join(
    f"Essay {i+1}:\n{essay}"
    for i, essay in enumerate(essays)
)

analysis_prompt = f"""Below are {NUM_ESSAYS} short college essay excerpts generated by a language model fine-tuned on 53 Ivy League college application essays. The model was given no prompt and generated freely.

{essays_text}

Please analyze these generations and identify:
1. Recurring themes or topics
2. Consistent writing patterns or stylistic quirks
3. Any apparent biases in content, tone, or worldview that likely reflect the training data
4. Recurring locations mentioned and family members, etc.

Be specific and concise."""

print("\nSending to Claude for analysis...")
client = anthropic.Anthropic()
message = client.messages.create(
    model="claude-sonnet-4-6",
    max_tokens=4096,
    messages=[{"role": "user", "content": analysis_prompt}],
)

print("\n" + "=" * 60)
print("CLAUDE'S ANALYSIS")
print("=" * 60)
print(message.content[0].text)
